// Converts `tmux capture-pane -p -e` output into styled segments for the landing page.
//
//   bun ansi-to-html.ts frame1.ansi frame2.ansi ... > tuiFrames.generated.ts
//
// Handles the SGR codes sprout emits: reset, bold, faint, reverse, 16/256/true
// colour foreground and background.

import { readFileSync } from "node:fs";

type Style = {
  fg?: string;
  bg?: string;
  bold?: boolean;
  faint?: boolean;
  reverse?: boolean;
};

const ANSI16 = [
  "#000000",
  "#cd3131",
  "#0dbc79",
  "#e5e510",
  "#2472c8",
  "#bc3fbc",
  "#11a8cd",
  "#e5e5e5",
  "#666666",
  "#f14c4c",
  "#23d18b",
  "#f5f543",
  "#3b8eea",
  "#d670d6",
  "#29b8db",
  "#ffffff",
];

function color256(n: number): string {
  if (n < 16) return ANSI16[n];
  if (n >= 232) {
    const v = 8 + (n - 232) * 10;
    return `rgb(${v},${v},${v})`;
  }
  const i = n - 16;
  const level = (x: number) => (x === 0 ? 0 : 55 + x * 40);
  return `rgb(${level(Math.floor(i / 36))},${level(Math.floor((i % 36) / 6))},${level(i % 6)})`;
}

function applySgr(style: Style, params: number[]): Style {
  const s = { ...style };
  for (let i = 0; i < params.length; i++) {
    const p = params[i];
    if (p === 0) {
      delete s.fg;
      delete s.bg;
      s.bold = s.faint = s.reverse = false;
    } else if (p === 1) s.bold = true;
    else if (p === 2) s.faint = true;
    else if (p === 22) s.bold = s.faint = false;
    else if (p === 7) s.reverse = true;
    else if (p === 27) s.reverse = false;
    else if (p >= 30 && p <= 37) s.fg = ANSI16[p - 30];
    else if (p >= 90 && p <= 97) s.fg = ANSI16[p - 90 + 8];
    else if (p >= 40 && p <= 47) s.bg = ANSI16[p - 40];
    else if (p >= 100 && p <= 107) s.bg = ANSI16[p - 100 + 8];
    else if (p === 39) delete s.fg;
    else if (p === 49) delete s.bg;
    else if (p === 38 || p === 48) {
      const key = p === 38 ? "fg" : "bg";
      if (params[i + 1] === 2) {
        s[key] = `rgb(${params[i + 2]},${params[i + 3]},${params[i + 4]})`;
        i += 4;
      } else if (params[i + 1] === 5) {
        s[key] = color256(params[i + 2]);
        i += 2;
      }
    }
  }
  return s;
}

export type Seg = {
  t: string;
  fg?: string;
  bg?: string;
  bold?: boolean;
  faint?: boolean;
};
export type Frame = Seg[][];

function resolve(style: Style): Omit<Seg, "t"> {
  let fg = style.fg;
  let bg = style.bg;
  if (style.reverse) [fg, bg] = [bg ?? "#0d1117", fg ?? "#e6edf3"];
  const out: Omit<Seg, "t"> = {};
  if (fg) out.fg = fg;
  if (bg) out.bg = bg;
  if (style.bold) out.bold = true;
  if (style.faint) out.faint = true;
  return out;
}

/** Parses ANSI text into lines of styled segments, merging neighbours with equal style. */
export function parseAnsi(input: string): Frame {
  let style: Style = {};
  const lines: Seg[][] = [[]];
  const re =
    // biome-ignore lint/suspicious/noControlCharactersInRegex: this pattern exists to match ANSI escape sequences
    /\x1b\[([0-9;]*)m|\x1b\[[0-9;?]*[A-Za-ln-z]|\x1b\][^\x07]*\x07|(\n)|([^\x1b\n]+)/g;
  for (const m of input.matchAll(re)) {
    if (m[2] !== undefined) {
      lines.push([]);
    } else if (m[3] !== undefined) {
      const line = lines[lines.length - 1];
      const next: Seg = { t: m[3], ...resolve(style) };
      const prev = line[line.length - 1];
      if (
        prev &&
        prev.fg === next.fg &&
        prev.bg === next.bg &&
        prev.bold === next.bold &&
        prev.faint === next.faint
      ) {
        prev.t += next.t;
      } else {
        line.push(next);
      }
    } else if (m[1] !== undefined) {
      style = applySgr(style, m[1] === "" ? [0] : m[1].split(";").map(Number));
    }
  }
  return lines;
}

if (import.meta.main) {
  const files = process.argv.slice(2);
  const frames = files.map((f) =>
    parseAnsi(readFileSync(f, "utf8").replace(/\n$/, "")),
  );
  console.log(
    "// Generated by apps/web/scripts/tui-demo/capture.sh. Do not edit.",
  );
  console.log("// Real frames of `sprout` running against the demo repo.");
  console.log(
    'import type { Frame } from "../../../scripts/tui-demo/ansi-to-html";',
  );
  console.log(`export const TUI_FRAMES: Frame[] = ${JSON.stringify(frames)};`);
}
